#!/usr/bin/env bun

// CyberStrike: builds the server as a NON-compiled node/bun ESM bundle for the
// Electron desktop sidecar (packages/desktop). This is separate from build.ts,
// which emits compiled single-file bun binaries per platform; this one produces
// a runnable JS bundle at dist/node/node.js (+ any .wasm) that the desktop's
// utilityProcess imports. It never touches the compiled-binary output.

import path from "path"
import fs from "fs"
import { fileURLToPath } from "url"
import { Script } from "@cyberstrike-io/script"

const filename = fileURLToPath(import.meta.url)
const dir = path.resolve(path.dirname(filename), "..")
process.chdir(dir)

// Ensure the models.dev snapshot exists (build.ts generates it during the
// compiled-binary build; the node bundle imports it dynamically). Generate it
// here if missing so a standalone node build works. Falls back to an empty
// snapshot when offline so the build never fails on a network hiccup.
const snapshotPath = path.join(dir, "src/provider/models-snapshot.ts")
if (!fs.existsSync(snapshotPath)) {
  const modelsUrl = process.env.CYBERSTRIKE_MODELS_URL || "https://models.dev"
  let modelsData = "{}"
  try {
    modelsData = process.env.MODELS_DEV_API_JSON
      ? await Bun.file(process.env.MODELS_DEV_API_JSON).text()
      : await fetch(`${modelsUrl}/api.json`).then((x) => x.text())
  } catch (error) {
    console.warn("build-node: failed to fetch models snapshot, writing empty snapshot", error)
  }
  await Bun.write(
    snapshotPath,
    `// Auto-generated by build-node.ts - do not edit\nexport const snapshot: Record<string, any> = ${modelsData}\n`,
  )
  console.log("Generated models-snapshot.ts")
}

// Load migrations exactly like build.ts so the bundle carries them (db.ts reads
// the CYBERSTRIKE_MIGRATIONS define, falling back to filesystem when undefined).
const migrationDirs = (await fs.promises.readdir(path.join(dir, "migration"), { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && /^\d{4}\d{2}\d{2}\d{2}\d{2}\d{2}/.test(entry.name))
  .map((entry) => entry.name)
  .sort()

const migrations = await Promise.all(
  migrationDirs.map(async (name) => {
    const file = path.join(dir, "migration", name, "migration.sql")
    const sql = await Bun.file(file).text()
    const match = /^(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})/.exec(name)
    const timestamp = match
      ? Date.UTC(
          Number(match[1]),
          Number(match[2]) - 1,
          Number(match[3]),
          Number(match[4]),
          Number(match[5]),
          Number(match[6]),
        )
      : 0
    return { sql, timestamp, name }
  }),
)
console.log(`Loaded ${migrations.length} migrations`)

const result = await Bun.build({
  // Our server core imports the `bun` module ($, readableStreamToText, semver,
  // Bun.serve, ...) throughout, so a pure node target cannot bundle it. Build
  // for the bun runtime; the sidecar bundle is loaded by a bun-capable host.
  target: "bun",
  conditions: ["bun", "node"],
  tsconfig: "./tsconfig.json",
  entrypoints: ["./src/node.ts"],
  outdir: "./dist/node",
  format: "esm",
  sourcemap: "linked",
  // jsonc-parser + node-pty resolve at runtime; electron/chromium-bidi never
  // belong in the server bundle (they'd only appear via a stray import).
  external: ["jsonc-parser", "@lydell/node-pty", "chromium-bidi", "electron"],
  define: {
    CYBERSTRIKE_VERSION: `'${Script.version}'`,
    CYBERSTRIKE_MIGRATIONS: JSON.stringify(migrations),
    CYBERSTRIKE_CHANNEL: `'${Script.channel}'`,
    CYBERSTRIKE_LIBC: process.platform === "linux" ? "'glibc'" : "",
  },
})

if (!result.success) {
  for (const message of result.logs) console.error(message)
  throw new Error("build-node: server bundle failed")
}

console.log("Build complete: dist/node/node.js")
