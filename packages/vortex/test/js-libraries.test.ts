describe("JS library fingerprint rules", () => {
  test("every rule has a sample and the sample fires it", () => {
    const ids = new Set(jsLibraryRules.map((r) => r.id))
    const sampled = new Set(samples.map(([id]) => id))
    // every rule is covered by a sample
    for (const id of ids) expect(sampled.has(id)).toBe(true)
    // every sample fires its target rule
    for (const [id, body] of samples) expect(fired(body)).toContain(id)
  })

  test("a plain page triggers no library rules", () => {
    expect(fired("<html><body>Hello world</body></html>")).toHaveLength(0)
  })

  test("all rule IDs start with tech-lib-", () => {
    for (const r of jsLibraryRules) expect(r.id).toMatch(/^tech-lib-/)
  })

  test("all rules have js-library tag", () => {
    for (const r of jsLibraryRules) expect(r.tags).toContain("js-library")
  })

  test("rule count is 192", () => {
    expect(jsLibraryRules.length).toBe(192)
  })
})
