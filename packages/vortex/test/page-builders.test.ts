describe("page builder fingerprint rules", () => {
  test("every rule has a sample and the sample fires it", () => {
    const ids = new Set(pageBuilderRules.map((r) => r.id))
    const sampled = new Set(samples.map(([id]) => id))
    for (const id of ids) expect(sampled.has(id)).toBe(true)
    for (const [id, body] of samples) expect(fired(body)).toContain(id)
  })

  test("a plain page triggers no page builder rules", () => {
    expect(fired("<html><body>Hello world</body></html>")).toHaveLength(0)
  })

  test("all rule IDs start with tech-pb-", () => {
    for (const r of pageBuilderRules) expect(r.id).toMatch(/^tech-pb-/)
  })

  test("all rules have page-builder tag", () => {
    for (const r of pageBuilderRules) expect(r.tags).toContain("page-builder")
  })

  test("rule count is 233", () => {
    expect(pageBuilderRules.length).toBe(233)
  })
})
