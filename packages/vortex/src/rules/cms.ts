// Category "technology", severity "info". Signals route to wstg-info-gathering for stack
// enumeration and CMS-specific (plugin/theme enumeration, admin path, known-CVE) surface mapping.
import type { DeclarativeRule } from "../declarative"

const cms = (id: string, name: string, when: string): DeclarativeRule => ({
  id,
  category: "technology",
  severity: "info",
  when,
  message: `CMS detected: ${name} at {endpoint}`,
  dedupBy: "host",
  tags: ["tech", "cms"],
})
const body = (id: string, name: string, pattern: string) => cms(id, name, `regex("${pattern}", resp.body)`)

