// Web server / HTTP daemon fingerprint rules. Detect the origin server or app server from the
// Server / X-Powered-By response headers (and a few body markers).
// Category "technology", severity "info". Signals route to wstg-info-gathering for infrastructure
// mapping and server-specific vuln-class (version disclosure, known CVE) surface mapping.
import type { DeclarativeRule } from "../declarative"

const ws = (id: string, name: string, when: string): DeclarativeRule => ({
  id,
  category: "technology",
  severity: "info",
  when,
  message: `Web server detected: ${name} at {host}`,
  dedupBy: "host",
  tags: ["tech", "web-server"],
})
// Server-header-only helper.
const srv = (id: string, name: string, pattern: string) => ws(id, name, `regex("${pattern}", resp.header.server)`)

